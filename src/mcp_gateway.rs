    fn attach_reasoning_context_v1(
        &self,
        exact: &mut Value,
        candidate: Box<dyn ReasoningContextCandidateV1>,
        connection: &StdioConnectionV1,
        request_id: &JsonRpcId,
    ) {
        let Ok(recipient) = connection.current_reasoning_recipient() else {
            return;
        };
        let scope = candidate.scope();
        if scope.authorization_scope_digest != connection.authorization_scope_digest {
            return;
        }
        let key = ReasoningDeliveryKeyV1::from_scope(connection.session_id, &scope, &recipient);
        let acknowledgment = self
            .reasoning_delivery_ledger
            .lock()
            .unwrap_or_else(|poison| poison.into_inner())
            .confirmed
            .get(&key)
            .cloned();
        let Ok(mut prepared) = candidate.compile(&recipient, acknowledgment.as_deref()) else {
            return;
        };
        if prepared.presentation == ReasoningTransportPresentationV1::Full
            && prepared.completion.is_none()
        {
            return;
        }
        let Some(object) = exact.as_object_mut() else {
            return;
        };
        let metadata = object
            .entry("_meta")
            .or_insert_with(|| Value::Object(Map::new()));
        let Some(metadata) = metadata.as_object_mut() else {
            return;
        };
        let again = metadata
            .entry("again")
            .or_insert_with(|| Value::Object(Map::new()));
        let Some(again) = again.as_object_mut() else {
            return;
        };
        let presentation = match prepared.presentation {
            ReasoningTransportPresentationV1::Full => "full",
            ReasoningTransportPresentationV1::CompactReference => "compact_reference",
        };
        again.insert(
            "reasoningContext".to_owned(),
            json!({
                "schemaVersion": 1,
                "presentation": presentation,
                "brief": prepared.brief,
                "metrics": prepared.metrics
            }),
        );
        if let Some(completion) = prepared.completion.take() {
            self.pending_reasoning_writes
                .lock()
                .unwrap_or_else(|poison| poison.into_inner())
                .insert(
                    (connection.session_id, request_id.clone()),
                    ReasoningWriteCompletionV1 {
                        key,
                        recipient,
                        completion,
                        lifecycle_generation: Arc::clone(&connection.lifecycle_generation),
                    },
                );
        }
    }

    fn confirm_reasoning_write_v1(&self, completion: ReasoningWriteCompletionV1) {
        if completion.lifecycle_generation.load(Ordering::Acquire)
            != completion.recipient.lifecycle_generation
        {
            return;
        }
        let acknowledgment = completion.completion.complete();
        if let Ok(acknowledgment) = acknowledgment {
            let mut ledger = self
                .reasoning_delivery_ledger
                .lock()
                .unwrap_or_else(|poison| poison.into_inner());
            // Completion may perform canonicalization between the first
            // lifecycle check and insertion. Recheck while holding the same
            // ledger lock used by invalidation so a disconnect, cancellation,
            // or compaction cannot race a retired acknowledgment back into the
            // live set.
            if completion.lifecycle_generation.load(Ordering::Acquire)
                != completion.recipient.lifecycle_generation
            {
                return;
            }
            ledger.remember(completion.key, acknowledgment);
            #[cfg(test)]
            self.reasoning_confirmation_count
                .fetch_add(1, Ordering::AcqRel);
        }
    }

    fn invalidate_reasoning_session_v1(&self, connection: &StdioConnectionV1) {
        connection
            .lifecycle_generation
            .fetch_add(1, Ordering::AcqRel);
        self.reasoning_delivery_ledger
            .lock()
            .unwrap_or_else(|poison| poison.into_inner())
            .retire_session(connection.session_id);
        self.pending_reasoning_writes
            .lock()
            .unwrap_or_else(|poison| poison.into_inner())
            .retain(|(session_id, _), _| *session_id != connection.session_id);
    }

    /// Parse one JSON-RPC frame, rejecting duplicate keys before constructing a
    /// request value.
    pub fn parse_message(&self, input: &[u8]) -> Result<Value, GatewayInputError> {
        parse_bounded_json(input, self.limits)
    }

    /// Process one newline-free stdio frame.  Framing/parser failures become
    /// typed JSON-RPC error responses with a null id.
    #[must_use]
    pub fn process_bytes(
        &self,
        input: &[u8],
        context: &GatewayRequestContext,
        secrets: EphemeralSecrets<'_>,
    ) -> Option<Vec<u8>> {
        self.process_bytes_inner(input, context, secrets, None, None)
    }

    fn process_bytes_inner(
        &self,
        input: &[u8],
        context: &GatewayRequestContext,
        secrets: EphemeralSecrets<'_>,
        activation: Option<&StdioActivationV1>,
        connection: Option<&StdioConnectionV1>,
    ) -> Option<Vec<u8>> {
        let response = match self.parse_message(input) {
            Ok(message) => self.handle_message(message, context, secrets, activation, connection),
            Err(error) => Some(error_response(Value::Null, input_error_to_mcp(&error))),
        };
        response.map(|mut value| {
            let pending = take_internal_delivery_v2(&mut value);
            let mut encoded = serde_json::to_vec(&value)
                .expect("JSON-RPC response values are always serializable");
            if let (Some(connection), Some((call_digest, captured))) = (connection, pending)
                && connection.delivery_protocol_enabled.load(Ordering::Acquire)
                && let Some(request_id) = value
                    .get("id")
                    .and_then(|id| JsonRpcId::from_value(id).ok())
            {
                let envelope_digest =
                    delivery_digest_v1(b"again.mcp.delivery-response-envelope.v2\0", &encoded);
                if let Ok(challenge) = self
                    .delivery_ledger
                    .lock()
                    .unwrap_or_else(|poison| poison.into_inner())
                    .issue(
                        connection,
                        &request_id,
                        call_digest,
                        captured,
                        envelope_digest,
                    )
                {
                    let notification = json!({
                        "jsonrpc": "2.0",
                        "method": "notifications/again/delivery-challenge",
                        "params": { "challenge": challenge }
                    });
                    encoded.push(b'\n');
                    encoded.extend_from_slice(
                        &serde_json::to_vec(&notification)
                            .expect("delivery challenge notifications are serializable"),
                    );
                }
            }
            encoded
        })
    }

