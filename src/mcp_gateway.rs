struct StdioConnectionV1 {
    session_id: u64,
    connection_digest: String,
    connection_generation: String,
    authorization_scope_digest: String,
    recipient: StdioRecipientV1,
    live_authority: Option<LiveConnectionAuthorityV2>,
    delivery_protocol_enabled: AtomicBool,
    compaction_generation: AtomicU64,
    lifecycle_generation: Arc<AtomicU64>,
}

impl StdioConnectionV1 {
    fn current_recipient(
        &self,
    ) -> Result<AuthenticatedStdioRecipientV1, DeliveryAuthorityRefusalV1> {
        match &self.recipient {
            StdioRecipientV1::Unknown => {
                Err(DeliveryAuthorityRefusalV1::UnsupportedRecipientAuthority)
            }
            StdioRecipientV1::Authenticated(recipient) => {
                let mut recipient = recipient.clone();
                recipient.compaction_generation =
                    self.compaction_generation.load(Ordering::Acquire);
                Ok(recipient)
            }
        }
    }

    fn current_reasoning_recipient(
        &self,
    ) -> Result<ReasoningTransportRecipientV1, DeliveryAuthorityRefusalV1> {
        let recipient = self.current_recipient()?;
        Ok(ReasoningTransportRecipientV1 {
            agent_id: recipient.agent_id,
            session_id: recipient.session_id,
            turn_id: recipient.turn_id,
            connection_generation: self.connection_digest.clone(),
            compaction_generation: self.compaction_generation.load(Ordering::Acquire),
            lifecycle_generation: self.lifecycle_generation.load(Ordering::Acquire),
        })
    }
}

impl StdioActivationV1 {
    fn signal(&self) {
        if self
            .signalled
            .compare_exchange(false, true, Ordering::AcqRel, Ordering::Acquire)
            .is_ok()
        {
            let _ = self.sender.send(());
        }
    }
}

