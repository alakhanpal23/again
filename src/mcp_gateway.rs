fn attach_internal_delivery_v2(
    response: &mut Value,
    call_digest: [u8; 32],
    delivery: CapturedDeliveryV1,
) {
    if let Some(object) = response.as_object_mut() {
        object.insert(
            INTERNAL_DELIVERY_FIELD_V2.to_owned(),
            json!({
                "callDigest": hex_v1(&call_digest),
                "gatewayResultId": delivery.gateway_result_id,
                "resultDigest": delivery.result_digest,
                "streams": delivery.streams,
            }),
        );
    }
}

fn take_internal_delivery_v2(value: &mut Value) -> Option<([u8; 32], CapturedDeliveryV1)> {
    let internal = value.as_object_mut()?.remove(INTERNAL_DELIVERY_FIELD_V2)?;
    let object = internal.as_object()?;
    let call_hex = object.get("callDigest")?.as_str()?;
    if call_hex.len() != 64 {
        return None;
    }
    let mut call_digest = [0_u8; 32];
    for (index, pair) in call_hex.as_bytes().chunks_exact(2).enumerate() {
        call_digest[index] = u8::from_str_radix(std::str::from_utf8(pair).ok()?, 16).ok()?;
    }
    let streams = serde_json::from_value(object.get("streams")?.clone()).ok()?;
    Some((
        call_digest,
        CapturedDeliveryV1 {
            gateway_result_id: object.get("gatewayResultId")?.as_str()?.to_owned(),
            result_digest: object.get("resultDigest")?.as_str()?.to_owned(),
            streams,
        },
    ))
}

